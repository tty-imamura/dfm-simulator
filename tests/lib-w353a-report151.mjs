/** 行を文に分ける —— 「。」で分けるが、『』「」の中の「。」では分けない(「。」で継ぐと原文の行に戻る) */
export function splitSent(line) {
  const out = []; let d = 0, cur = '';
  for (const ch of String(line)) {
    if (ch === '『' || ch === '「') d++;
    else if ((ch === '』' || ch === '」') && d > 0) d--;
    if (ch === '。' && d === 0) { out.push(cur); cur = ''; continue; }
    cur += ch;
  }
  out.push(cur);
  return out;
}
